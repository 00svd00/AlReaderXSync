package ru.samorez.alreaderxsync.data

/**
 * Режимы синхронизации.
 *
 * Сравнение файлов происходит по ИМЕНИ (relativePath) и РАЗМЕРУ.
 * Для файлов с расширениями .db, .sqlite, .ini, .profile
 * дополнительно сравнивается SHA-256 содержимого (contentHash).
 * mtime НЕ используется — при записи через SAF он устанавливается
 * в текущее время, а не копируется из источника.
 *
 * Имена констант сохранены для обратной совместимости с существующим
 * кодом; фактическая семантика отражена в комментариях и UI-названиях.
 */
enum class SyncMode {

    /**
     * «Замена».
     *
     * Приводит target в точное соответствие с source:
     *  - передаются отсутствующие или несовпадающие файлы;
     *  - удаляются файлы target, отсутствующие в source.
     *
     * Совпадающие по имени и размеру файлы НЕ передаются.
     *
     * UI-название: «Замена».
     */
    FULL_REPLACE,

    /**
     * «Объединение».
     *
     * Добавляет файлы source в target, не удаляя существующие:
     *  - передаются отсутствующие или несовпадающие файлы;
     *  - лишние файлы target остаются без изменений.
     *
     * Совпадающие по имени и размеру файлы НЕ передаются.
     *
     * UI-название: «Объединение».
     */
    MERGE_NEWEST_WINS
}

/**
 * Человекочитаемое название режима для отображения в UI.
 *
 * Рекомендуется использовать в UI-слое. Для полноценной локализации
 * в будущем можно заменить на возврат строковых ресурсов
 * (`displayNameRes(): Int`).
 */
fun SyncMode.displayName(): String = when (this) {
    SyncMode.FULL_REPLACE -> "Замена"
    SyncMode.MERGE_NEWEST_WINS -> "Объединение"
}